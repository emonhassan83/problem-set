SELECT * FROM employees;
SELECT count(*) FROM employees;

--* 1. create simple FUNCTION
CREATE FUNCTION emp_count()
    RETURNS INT
    LANGUAGE SQL
    AS
    $$
        SELECT count(*) FROM employees;
    $$;

--* Execution function
SELECT emp_count();

--* 2. create FUNCTION (delete 30 no COLUMN)
CREATE OR replace FUNCTION delete_emp()
    RETURNS void
    LANGUAGE SQL
    AS
    $$
        DELETE FROM employees WHERE employee_id = 30;
    $$;

SELECT delete_emp();

--* 3. use parameter in function(to delete user)
CREATE OR replace FUNCTION delete_emp_by_id(p_emp_id INT)
    RETURNS void
    LANGUAGE SQL
    AS
    $$
        DELETE FROM employees WHERE employee_id = p_emp_id;
    $$;

SELECT delete_emp_by_id(29);

--* 1. create procedure
CREATE PROCEDURE remove_emp_var()
    LANGUAGE plpgsql
    AS
    $$
        BEGIN
            DELETE FROM employees WHERE employee_id = 28;
        END
    $$;

--* Execution procedure
CALL remove_emp_var();

--* 2. create procedure with variable
CREATE PROCEDURE remove_emp_variable()
    LANGUAGE plpgsql
    AS
    $$
        DECLARE
        test_var int;
        BEGIN
            SELECT employee_id INTO test_var FROM employees WHERE employee_id = 27;
            DELETE FROM employees WHERE employee_id = test_var;
        END
    $$;

call remove_emp_variable();

--* pass parameter in procedure with variable and return a massage
CREATE Procedure remove_emp_by_id(p_emp_id INT)
    LANGUAGE plpgsql
    AS
    $$
        DECLARE
        test_var INT;
        BEGIN
            SELECT employee_id INTO test_var FROM employees WHERE employee_id = p_emp_id;
            DELETE FROM employees WHERE employee_id = test_var;

            RAISE NOTICE 'Employee removed successfully!';
        END
    $$;

CALL remove_emp_by_id(26);